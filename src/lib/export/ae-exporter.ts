/**
 * Check if corners are default (unmodified quad)
 */
function isDefaultCorners(corners: { x: number; y: number }[]): boolean {
    if (corners.length !== 4) return false;

    const defaultCorners = [
        { x: -0.5, y: 0.5 },
        { x: 0.5, y: 0.5 },
        { x: 0.5, y: -0.5 },
        { x: -0.5, y: -0.5 }
    ];

    const tolerance = 0.001;
    return corners.every((corner, i) =>
        Math.abs(corner.x - defaultCorners[i].x) < tolerance &&
        Math.abs(corner.y - defaultCorners[i].y) < tolerance
    );
}

/**
 * Convert hex color to RGB array (0-1)
 */
function hexToRGB(hex: string): [number, number, number] {
    const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
    return result ? [
        parseInt(result[1], 16) / 255,
        parseInt(result[2], 16) / 255,
        parseInt(result[3], 16) / 255
    ] : [0.5, 0.5, 0.5];
}
