import { Scene, Surface, MediaAsset } from "@/store/project-store";
import { ExportOptions, BLEND_MODE_MAP } from "./export-types";

/**
 * Export ProjectionX project to After Effects JSX script
 */
export async function exportToAfterEffects(
    scenes: Scene[],
    mediaAssets: MediaAsset[],
    options: ExportOptions
): Promise<Blob> {
    const jsxScript = generateAEScript(scenes, mediaAssets, options);
    return new Blob([jsxScript], { type: "application/javascript" });
}

/**
 * Generate After Effects ExtendScript JSX
 */
function generateAEScript(
    scenes: Scene[],
    mediaAssets: MediaAsset[],
    options: ExportOptions
): string {
    const projectName = options.projectName || "ProjectionX Export";

    let script = `// After Effects JSX Script
// Generated by ProjectionX
// Project: ${projectName}

app.beginUndoGroup("Import ProjectionX Project");

try {
    var project = app.project;

    // Create folder for compositions
    var compFolder = project.items.addFolder("${projectName}");

`;

    // Import footage items
    const footageMap: Record<string, string> = {};
    mediaAssets.forEach((asset, index) => {
        if (asset.type === "image" || asset.type === "video") {
            const footageName = `footage_${index + 1}`;
            footageMap[asset.id] = footageName;

            script += `    // Import: ${asset.name}
    // Note: Update this path to match your media location
    // var ${footageName} = project.importFile(new ImportOptions(File("${asset.url}")));
    // ${footageName}.parentFolder = compFolder;

`;
        }
    });

    // Create composition for each scene
    scenes.forEach((scene, sceneIndex) => {
        script += generateSceneComposition(scene, mediaAssets, footageMap, options, sceneIndex + 1);
    });

    script += `
} catch (e) {
    alert("Error importing ProjectionX project: " + e.toString());
}

app.endUndoGroup();
`;

    return script;
}

/**
 * Generate composition for a scene
 */
function generateSceneComposition(
    scene: Scene,
    mediaAssets: MediaAsset[],
    footageMap: Record<string, string>,
    options: ExportOptions,
    sceneNumber: number
): string {
    const { width, height } = options.resolution;
    const { frameRate } = options;
    const duration = scene.timelineDuration || 30;

    let script = `    // Scene ${sceneNumber}: ${scene.name}
    var comp${sceneNumber} = compFolder.items.addComp("${scene.name}", ${width}, ${height}, 1, ${duration}, ${frameRate});

`;

    // Add layers for each surface (reverse order for correct stacking)
    const sortedSurfaces = [...scene.surfaces].sort((a, b) => a.zIndex - b.zIndex).reverse();

    sortedSurfaces.forEach((surface, index) => {
        script += generateSurfaceLayer(surface, mediaAssets, footageMap, sceneNumber, index + 1, options);
    });

    return script;
}

/**
 * Generate layer for a surface
 */
function generateSurfaceLayer(
    surface: Surface,
    mediaAssets: MediaAsset[],
    footageMap: Record<string, string>,
    compNum: number,
    layerNum: number,
    options: ExportOptions
): string {
    const media = surface.mediaId ? mediaAssets.find(m => m.id === surface.mediaId) : null;
    const hasMedia = media && (media.type === "image" || media.type === "video");

    let script = `    // Layer: ${surface.name}
`;

    if (hasMedia && footageMap[surface.mediaId!]) {
        // Create layer from footage
        script += `    // var layer${layerNum} = comp${compNum}.layers.add(${footageMap[surface.mediaId!]});
    var layer${layerNum} = comp${compNum}.layers.addSolid([1, 1, 1], "${surface.name}", ${options.resolution.width}, ${options.resolution.height}, 1);
`;
    } else {
        // Create solid layer
        const color = media?.type === "color" && media.color ? hexToRGB(media.color) : [0.5, 0.5, 0.5];
        script += `    var layer${layerNum} = comp${compNum}.layers.addSolid([${color[0]}, ${color[1]}, ${color[2]}], "${surface.name}", ${options.resolution.width}, ${options.resolution.height}, 1);
`;
    }

    // Set layer properties
    script += `    layer${layerNum}.name = "${surface.name}";
    layer${layerNum}.startTime = ${surface.startTime};

`;

    // Position (convert from ProjectionX coordinates to AE coordinates)
    const posX = options.resolution.width / 2 + surface.position.x;
    const posY = options.resolution.height / 2 - surface.position.y; // Flip Y
    script += `    layer${layerNum}.property("Transform").property("Position").setValue([${posX}, ${posY}]);
`;

    // Rotation (convert radians to degrees)
    const rotationDeg = (surface.rotation * 180 / Math.PI);
    script += `    layer${layerNum}.property("Transform").property("Rotation").setValue(${rotationDeg});
`;

    // Scale (convert to percentage)
    const scaleX = surface.scale.x * 100;
    const scaleY = surface.scale.y * 100;
    script += `    layer${layerNum}.property("Transform").property("Scale").setValue([${scaleX}, ${scaleY}]);
`;

    // Opacity (convert 0-1 to 0-100)
    const opacity = surface.opacity * 100;
    script += `    layer${layerNum}.property("Transform").property("Opacity").setValue(${opacity});
`;

    // Blend mode
    const blendMode = BLEND_MODE_MAP[surface.blendMode] || "NORMAL";
    script += `    layer${layerNum}.blendingMode = BlendingMode.${blendMode};
`;

    // Corner Pin effect if corners are not default
    const hasCornerPin = !isDefaultCorners(surface.corners);
    if (hasCornerPin) {
        script += generateCornerPinEffect(surface, layerNum, options);
    }

    // Effects
    if (media?.type !== "video" && media?.type !== "image") {
        // Add brightness/contrast, hue/saturation, blur effects
        // Note: Only add effects for generated content, not footage
        script += generateEffects(surface, layerNum);
    }

    script += `
`;

    return script;
}

/**
 * Generate Corner Pin effect
 */
function generateCornerPinEffect(surface: Surface, layerNum: number, options: ExportOptions): string {
    // Convert normalized corners to pixel coordinates
    const width = options.resolution.width;
    const height = options.resolution.height;

    // ProjectionX corners are in normalized space (-0.5 to 0.5)
    // Convert to AE pixel space
    const corners = surface.corners.map(c => [
        width / 2 + c.x * surface.scale.x,
        height / 2 - c.y * surface.scale.y // Flip Y
    ]);

    return `
    // Corner Pin
    var cornerPinEffect = layer${layerNum}.property("Effects").addProperty("ADBE Corner Pin");
    cornerPinEffect.property("ADBE Corner Pin-0001").setValue([${corners[0][0]}, ${corners[0][1]}]); // Upper Left
    cornerPinEffect.property("ADBE Corner Pin-0002").setValue([${corners[1][0]}, ${corners[1][1]}]); // Upper Right
    cornerPinEffect.property("ADBE Corner Pin-0003").setValue([${corners[2][0]}, ${corners[2][1]}]); // Lower Right
    cornerPinEffect.property("ADBE Corner Pin-0004").setValue([${corners[3][0]}, ${corners[3][1]}]); // Lower Left
`;
}

